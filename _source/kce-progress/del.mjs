import { chromium } from 'playwright';
import { initializeTestEnvironment } from '@firebase/rules-unit-testing';
import { readFileSync } from 'fs';
import { doc, setDoc, Timestamp } from 'firebase/firestore';
const env = await initializeTestEnvironment({ projectId: 'kce-student-progress', firestore: { rules: readFileSync('firestore.rules','utf8'), host:'127.0.0.1', port:8080 } });
await env.clearFirestore();
await env.withSecurityRulesDisabled(async c => { const db=c.firestore();
  await setDoc(doc(db,'families/a'),{name:'Tia',parentEmails:['t@example.com']});
  await setDoc(doc(db,'families/a/students/bristol'),{firstName:'Bristol',courses:['bb-bristol']});
  await setDoc(doc(db,'families/b'),{name:'Tia',parentEmails:[]});
  await setDoc(doc(db,'families/b/students/bailey'),{firstName:'Bailey',courses:['bb-bailey']});
  await setDoc(doc(db,'families/b/students/bailey/events/e1'),{course:'bb-bailey',score:50,at:Timestamp.now()});
  await setDoc(doc(db,'families/b/students/bailey/progress/bb-bailey'),{items:{},updatedAt:Timestamp.now()});
});
const BASE='http://127.0.0.1:8080/v1/projects/kce-student-progress/databases/(default)/documents/'; const H={headers:{Authorization:'Bearer owner'}};
const list=async p=>((await (await fetch(BASE+p,H)).json()).documents||[]);
let pass=0,fail=0; const ok=(n,c)=>{ if(c){pass++;console.log('  ok  ',n)} else {fail++;console.log('  FAIL',n)} };
const b=await chromium.launch(); const ctx=await b.newContext(); await ctx.route('https://formspree.io/**', r=>r.fulfill({status:200,body:'{}',contentType:'application/json'})); const A=await ctx.newPage(); let ans=true; A.on('dialog',d=>ans?d.accept():d.dismiss());
await A.goto('http://127.0.0.1:8765/kce-progress/dashboard.html'); await A.waitForSelector('#in');
await A.evaluate(()=>window.__kcepTestSignIn('kce@kingcretot.com')); await A.waitForSelector('text=Every student',{timeout:20000});
await A.click('text=Families & enrollment'); await A.waitForSelector('[data-f="b"] [data-del-fam]');
ans=false; await A.click('[data-f="b"] [data-del-fam]'); await new Promise(r=>setTimeout(r,1500));
ok('Cancel keeps the family', (await list('families')).length===2);
ans=true; await A.click('[data-f="b"] [data-del-fam]'); await new Promise(r=>setTimeout(r,3000));
const f=await list('families');
ok('Remove deletes only that family', f.length===1 && f[0].name.endsWith('/a'));
ok("and its child's scores and progress", (await list('families/b/students/bailey/events')).length===0 && (await list('families/b/students/bailey/progress')).length===0 && (await list('families/b/students')).length===0);
ok('other family untouched', (await list('families/a/students')).length===1);
console.log(`\n${pass} passed, ${fail} failed`); await b.close(); await env.cleanup(); process.exit(fail?1:0);
